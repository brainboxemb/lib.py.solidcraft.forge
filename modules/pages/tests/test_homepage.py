import json
from pathlib import Path
from tempfile import TemporaryDirectory
import unittest

from cad_library_pages.homepage import homepage_manifest, prepare_homepage


class HomepageTests(unittest.TestCase):
    def _root(self, text: str):
        tmp = TemporaryDirectory()
        root = Path(tmp.name)
        (root / "site").mkdir()
        (root / "site/home.yml").write_text(text, encoding="utf-8")
        self.addCleanup(tmp.cleanup)
        return root

    def test_generated_values_are_resolved_before_hugo(self):
        root = self._root(
            """schema: 1
blocks:
  - type: hero
    eyebrow: Forge
    title: Generated home
    lead: Generated by Pages.
    badges:
      - SCPF ${package_version}
    actions:
      - label: Models
        url: https://example.org/models/
"""
        )
        site = root / "prepared-site"
        prepare_homepage(
            root,
            site,
            context={"package_version": "1.2.3"},
        )
        data = json.loads((site / "data/home.json").read_text(encoding="utf-8"))
        self.assertEqual(data["blocks"][0]["badges"], ["SCPF 1.2.3"])
        self.assertTrue(data["blocks"][0]["actions"][0]["external"])

    def test_unknown_generated_value_fails_closed(self):
        root = self._root(
            """schema: 1
blocks:
  - type: hero
    eyebrow: Forge
    title: Generated home
    lead: Missing ${unknown_value}.
"""
        )
        with self.assertRaisesRegex(ValueError, "unknown generated value"):
            homepage_manifest(root, context={})

    def test_destination_must_choose_route_or_url(self):
        root = self._root(
            """schema: 1
blocks:
  - type: hero
    eyebrow: Forge
    title: Broken
    lead: Invalid destination.
    actions:
      - label: Invalid
        route: guide/
        url: https://example.org/
"""
        )
        with self.assertRaisesRegex(ValueError, "exactly one of route or url"):
            homepage_manifest(root)


if __name__ == "__main__":
    unittest.main()
